// probeRoot builds a synthetic tree with the shape that matters here:
// nested subcommands, local flags, and a persistent flag on the root.
//
// The leaves carry a Run, and that is load-bearing rather than
// decorative. cobra renders only commands where IsAvailableCommand() is
// true, and a command is unavailable when it is neither runnable nor the
// parent of something runnable. A fixture built from bare Use/Short
// pairs therefore renders exactly one page - the root - and the
// generator looks broken when it is behaving correctly. The same rule
// applies to the real trees: a group command whose children all lose
// their Run would silently drop out of the reference.
func probeRoot() *cobra.Command {
	noop := func(*cobra.Command, []string) {}

	root := &cobra.Command{Use: "probectl", Short: "Probe control CLI"}
	root.PersistentFlags().String("control-addr", "", "Control address")

	agent := &cobra.Command{Use: "agent", Short: "Agent operations"}
	build := &cobra.Command{
		Use:   "build",
		Short: "Build an agent",
		Long:  "Builds an agent from source.",
		Run:   noop,
	}
	build.Flags().Bool("cgo", false, "Enable cgo")
	agent.AddCommand(build)

	root.AddCommand(agent)
	root.AddCommand(&cobra.Command{Use: "ping", Short: "Ping the daemon", Run: noop})
	return root
}

func renderedFiles(t *testing.T, dir string) []string {
	t.Helper()
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	var out []string
	for _, e := range entries {
		out = append(out, e.Name())
	}
	sort.Strings(out)
	return out
}

func TestCLI_RendersEveryCommandInTheTree(t *testing.T) {
	dir := t.TempDir()
	if err := docsgen.CLI(probeRoot(), dir); err != nil {
		t.Fatalf("CLI: %v", err)
	}
	want := []string{
		"probectl.md",
		"probectl_agent.md",
		"probectl_agent_build.md",
		"probectl_ping.md",
	}
	got := renderedFiles(t, dir)
	if strings.Join(got, ",") != strings.Join(want, ",") {
		t.Errorf("rendered %v, want %v", got, want)
	}
}

func TestCLI_WritesRelearnFrontMatterWithTheCommandPath(t *testing.T) {
	dir := t.TempDir()
	if err := docsgen.CLI(probeRoot(), dir); err != nil {
		t.Fatal(err)
	}
	body, err := os.ReadFile(filepath.Join(dir, "probectl_agent_build.md"))
	if err != nil {
		t.Fatal(err)
	}
	s := string(body)
	if !strings.HasPrefix(s, "---\n") {
		t.Error("page does not start with front matter")
	}
	if !strings.Contains(s, `title: "probectl agent build"`) {
		t.Errorf("front matter title is not the command path:\n%s", firstLine(s))
	}
	if !strings.Contains(s, "--cgo") {
		t.Error("the command's own flag is missing from its page")
	}
}

// THE TRAP THE WHOLE DRIFT GATE TURNS ON. Cobra stamps a generated-on
// date unless DisableAutoGenTag is set, and it must be set on every
// command rather than the root, because each is constructed separately
// and carries its own zero value.
func TestCLI_CarriesNoGeneratedOnDate(t *testing.T) {
	dir := t.TempDir()
	if err := docsgen.CLI(probeRoot(), dir); err != nil {
		t.Fatal(err)
	}
	year := strconv.Itoa(time.Now().Year())
	for _, name := range renderedFiles(t, dir) {
		body, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			t.Fatal(err)
		}
		s := string(body)
		if strings.Contains(s, "Auto generated by spf13/cobra") {
			t.Errorf("%s carries cobra's auto-generated tag, which contains a date", name)
		}
		if strings.Contains(s, year) {
			t.Errorf("%s contains the current year, so the page is a function of the clock", name)
		}
	}
}

func TestCLI_IsDeterministic(t *testing.T) {
	a, b := t.TempDir(), t.TempDir()
	if err := docsgen.CLI(probeRoot(), a); err != nil {
		t.Fatal(err)
	}
	if err := docsgen.CLI(probeRoot(), b); err != nil {
		t.Fatal(err)
	}
	for _, name := range renderedFiles(t, a) {
		x, err := os.ReadFile(filepath.Join(a, name))
		if err != nil {
			t.Fatal(err)
		}
		y, err := os.ReadFile(filepath.Join(b, name))
		if err != nil {
			t.Fatal(err)
		}
		if string(x) != string(y) {
			t.Errorf("%s differs between two renders of one tree", name)
		}
	}
}

