func TestMan_RendersOnePagePerCommand(t *testing.T) {
	dir := t.TempDir()
	if err := docsgen.Man(probeRoot(), dir, "0.1.0-proto2k"); err != nil {
		t.Fatalf("Man: %v", err)
	}
	want := []string{"probectl-agent-build.1", "probectl-agent.1", "probectl-ping.1", "probectl.1"}
	got := renderedFiles(t, dir)
	if strings.Join(got, ",") != strings.Join(want, ",") {
		t.Errorf("rendered %v, want %v", got, want)
	}
}

// GenManHeader stamps time.Now() when Date is nil, which makes every
// regeneration produce different bytes and reads, under a byte-comparing
// gate, as "the CLI changed" on a tree where nothing changed.
func TestMan_CarriesTheInjectedVersionAndNoClock(t *testing.T) {
	dir := t.TempDir()
	if err := docsgen.Man(probeRoot(), dir, "0.1.0-proto2k"); err != nil {
		t.Fatal(err)
	}
	body, err := os.ReadFile(filepath.Join(dir, "probectl.1"))
	if err != nil {
		t.Fatal(err)
	}
	s := string(body)
	if !strings.Contains(s, "0.1.0-proto2k") {
		t.Errorf("man page does not name the injected version:\n%s", firstLine(s))
	}
	if strings.Contains(s, strconv.Itoa(time.Now().Year())) {
		t.Errorf("man page contains the current year, so it is a function of the clock:\n%s", firstLine(s))
	}
}

func TestMan_RefusesAnEmptyVersion(t *testing.T) {
	if err := docsgen.Man(probeRoot(), t.TempDir(), ""); err == nil {
		t.Fatal("an empty version must be refused; cobra would stamp the clock instead")
	}
}

func TestMan_IsDeterministic(t *testing.T) {
	a, b := t.TempDir(), t.TempDir()
	if err := docsgen.Man(probeRoot(), a, "1.0.0"); err != nil {
		t.Fatal(err)
	}
	if err := docsgen.Man(probeRoot(), b, "1.0.0"); err != nil {
		t.Fatal(err)
	}
	for _, name := range renderedFiles(t, a) {
		x, _ := os.ReadFile(filepath.Join(a, name))
		y, _ := os.ReadFile(filepath.Join(b, name))
		if string(x) != string(y) {
			t.Errorf("%s differs between two renders of one tree", name)
		}
	}
}

// Section 7 is the one written page. It goes through go-md2man, which is
// vendored for cobra's man generator anyway, which is what lets pandoc
// leave the flakes.
func TestOverview_ConvertsMarkdownAndDropsFrontMatter(t *testing.T) {
	dir := t.TempDir()
	src := filepath.Join(dir, "overview.md")
	out := filepath.Join(dir, "probe.7")
	page := "---\ntitle: \"Overview\"\n---\n\n# Probe\n\nProbe supervises agents.\n"
	if err := os.WriteFile(src, []byte(page), 0o600); err != nil {
		t.Fatal(err)
	}

	if err := docsgen.Overview(src, out, "probe", "1.0.0"); err != nil {
		t.Fatalf("Overview: %v", err)
	}
	body, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	s := string(body)
	if !strings.HasPrefix(s, `.TH PROBE 7 "1.0.0"`) {
		t.Errorf("section 7 header is wrong:\n%s", firstLine(s))
	}
	if !strings.Contains(s, "Probe supervises agents.") {
		t.Error("the page body did not survive conversion")
	}
	if strings.Contains(s, "title:") {
		t.Error("Hugo front matter leaked into the roff output")
	}
}
